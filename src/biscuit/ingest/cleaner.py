"""Derived view cleaners: blockquote pointer transformation, bot pruning, and CRLF normalization.

CRITICAL INVARIANT:
Cleaners are used solely to generate derived_cleaned_content and derived_normalized_content.
They are NEVER applied to raw_content, content_hash, or evidence offsets.
"""

import re

# Known bot usernames and indicators
BOT_USERNAMES = {
    "github-actions[bot]",
    "dependabot[bot]",
    "cla-bot",
    "stale[bot]",
    "codecov[bot]",
    "bors",
    "homu",
    "k8s-ci-robot",
    "google-cla-bot",
}

BOT_PATTERNS = [
    re.compile(r"^<!--\s*bot-comment\s*-->", re.IGNORECASE),
    re.compile(r"This is an automated (message|response|notification)", re.IGNORECASE),
    re.compile(r"I am a bot, and this action was performed automatically", re.IGNORECASE),
    re.compile(r"Please sign the Contributor License Agreement", re.IGNORECASE),
]

# Discourse quote pattern: [quote="username, post:N, topic:M"]...[/quote]
DISCOURSE_QUOTE_PATTERN = re.compile(
    r'\[quote="?(?P<author>[^,"]+)?(?:,\s*post:(?P<post>\d+))?(?:,\s*topic:(?P<topic>\d+))?"?\][\s\S]*?\[/quote\]',
    re.MULTILINE,
)

# Markdown blockquote pattern (multiline > blocks)
MARKDOWN_QUOTE_PATTERN = re.compile(
    r"(?:^[ \t]*>[ \t]?[^\n]*\n?)+",
    re.MULTILINE,
)


def normalize_line_endings(text: str) -> str:
    """Normalize CRLF (\\r\\n) and CR (\\r) to LF (\\n) for derived retrieval views."""
    if not text:
        return text
    return text.replace("\r\n", "\n").replace("\r", "\n")


def is_bot_message(author_handle: str, content: str) -> bool:
    """Determine whether a message was generated by an automated bot."""
    if author_handle:
        clean_handle = author_handle.strip().lower()
        if clean_handle in BOT_USERNAMES or clean_handle.endswith("[bot]"):
            return True

    if not content:
        return False

    first_chunk = content[:500]
    for pattern in BOT_PATTERNS:
        if pattern.search(first_chunk):
            return True

    return False


def replace_discourse_quotes(text: str) -> str:
    """Replace Discourse [quote=...] BBCode blocks with concise pointer references."""
    def _quote_replacer(match: re.Match) -> str:
        author = match.group("author") or "someone"
        post_num = match.group("post")
        if post_num:
            return f"[Quoting post-{post_num} by @{author.strip()}]\n"
        return f"[Quoting @{author.strip()}]\n"

    return DISCOURSE_QUOTE_PATTERN.sub(_quote_replacer, text)


def replace_markdown_quotes(text: str) -> str:
    """Replace Markdown blockquotes (> ...) with a pointer reference placeholder."""
    def _md_quote_replacer(match: re.Match) -> str:
        quote_body = match.group(0).strip()
        lines = [line.lstrip("> ").strip() for line in quote_body.splitlines() if line.strip()]
        first_line = lines[0] if lines else ""
        if len(first_line) > 60:
            first_line = first_line[:57] + "..."
        return f"[Quoting: \"{first_line}\"]\n\n"

    return MARKDOWN_QUOTE_PATTERN.sub(_md_quote_replacer, text)


def clean_derived_content(raw_text: str, platform_type: str | None = None) -> str:
    """Produce derived noise-filtered text for downstream LLM analysis.

    Replaces nested blockquotes with compact pointer references,
    normalizes CRLF to LF, and collapses excessive blank lines.
    Does NOT touch the raw untouched wire text.
    """
    if not raw_text:
        return ""

    cleaned = normalize_line_endings(raw_text)

    # Replace Discourse BBCode quotes if present
    cleaned = replace_discourse_quotes(cleaned)

    # Replace Markdown blockquotes
    cleaned = replace_markdown_quotes(cleaned)

    # Collapse excessive blank lines (3+ into 2)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)

    return cleaned.strip()
